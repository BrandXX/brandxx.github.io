import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { parse } from 'parse5';
import { documents } from './theme-documents.mjs';

const output = path.resolve('dist');
const attr = (node, name) => node.attrs?.find(item => item.name === name)?.value;
const walk = node => [node, ...(node.childNodes || []).flatMap(walk)];
async function files(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) result.push(...(await files(path.join(directory, entry.name))).map(file => path.join(entry.name, file)));
    else result.push(entry.name);
  }
  return result;
}

const entries = await files(output);
assert.equal(entries.some(file => /(^|\/)(\.staging|source-docs|node_modules|\.git|preview-assets)(\/|$)|master.career|source.of.truth|\.zip$/i.test(file)), false, 'Private or staging files in production output');
assert.equal((await readFile(path.join(output, 'CNAME'), 'utf8')).trim(), 'techsoftsys.com');
assert.equal(await readFile(path.join(output, 'robots.txt'), 'utf8'), await readFile('public/robots.txt', 'utf8'));
assert.match(await readFile(path.join(output, 'robots.txt'), 'utf8'), /Allow: \//);
assert.match(await readFile(path.join(output, 'sitemap-index.xml'), 'utf8'), /https:\/\/techsoftsys\.com\/sitemap-0.xml/);
assert.match(await readFile(path.join(output, 'sitemap-0.xml'), 'utf8'), /https:\/\/techsoftsys\.com\/about/);

const siteRoutes = ['', 'about', 'ai-lab', 'open-source', 'services', 'training', 'work', 'work/on-prem-llm-platform', 'work/downtime-reduction-program', 'work/zero-loss-virtualization-migration'];
for (const doc of [...siteRoutes.map(route => ({ file: route ? `${route}/index.html` : 'index.html', route: route ? `/${route}/` : '/', kind: 'site' })), ...documents]) {
  const html = await readFile(path.join(output, doc.file), 'utf8');
  const nodes = walk(parse(html));
  const robots = nodes.filter(node => node.tagName === 'meta' && attr(node, 'name') === 'robots').map(node => attr(node, 'content'));
  assert.deepEqual(robots, doc.kind === 'resume-print' ? ['noindex, follow'] : [], `Indexing policy changed: ${doc.file}`);
  const canonical = nodes.find(node => node.tagName === 'link' && attr(node, 'rel') === 'canonical');
  assert.equal(attr(canonical, 'href'), `https://techsoftsys.com${doc.route}`, `Incorrect canonical: ${doc.file}`);
  assert.equal(nodes.filter(node => node.tagName === 'main').length, 1, `Duplicate main: ${doc.file}`);
  assert.equal(nodes.filter(node => node.tagName === 'link' && attr(node, 'href') === '/document-assets/documents.css').length, 1);
  assert.equal(html.includes('/preview-assets/'), false);
  assert.equal(html.includes('localhost:'), false);
  if (doc.pdf) {
    assert.equal(nodes.filter(node => attr(node, 'data-preview-print') === doc.kind).length, 2, `Missing print controls: ${doc.file}`);
  }
}

// Downloads and artwork are release inputs, never regenerated by the theme build.
for (const directory of ['pdfs', 'branding', 'defiantly_not_regex']) {
  for (const file of await files(path.join('public', directory))) {
    if (file.endsWith('.html')) continue;
    const relative = path.join(directory, file);
    assert.deepEqual(await readFile(path.join(output, relative)), await readFile(path.join('public', relative)), `Asset changed: ${relative}`);
  }
}
console.log(`Production guards passed: ${entries.length} files; indexing, domain, document controls, downloads, artwork, and archive exclusion verified.`);
